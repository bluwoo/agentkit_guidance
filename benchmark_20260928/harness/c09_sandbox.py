"""Component: **agentkit-sandbox** (isolated code/command execution).

Per the Skill:
  * Agent calls the ``run_code`` tool; same ``session_id`` reuses one sandbox instance
    (shared filesystem), different sessions are isolated.
  * Real run_code needs ``AGENTKIT_TOOL_ID`` + a cloud sandbox Tool (CloudBoundary).
  * Three-layer permission model: sandbox mode (read-only / workspace-write /
    danger-full-access), approval policy (untrusted / on-request / never), reviewer.

We run code for real in a local subprocess with a per-session workspace dir, capturing
stdout + exit code and proving session filesystem reuse. No cloud, no AK/SK.

Default-deny machine guard (iteration2, slice B)
-------------------------------------------------
Every child process launched by :meth:`LocalSandbox.exec_code` is mediated by a generated
``sitecustomize.py`` injected via ``PYTHONPATH``. By default the child:

  * CANNOT open outbound TCP connections (``socket.socket.connect`` / ``connect_ex``);
  * CANNOT invoke known cloud-write CLIs (``aws s3*``, ``gcloud storage cp``, ``tosutil``,
    ``huggingface-cli upload``, ``twine upload``, ``npm publish``, ``docker push`` ...);
  * CANNOT read shell profiles (``~/.zshrc`` etc.) or common secret paths
    (``~/.aws/``, ``~/.ssh/``, ``~/.netrc`` ...). The guard *matches path names only* —
    it never opens or reads those files.

Explicit opt-out (tests only)
~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
Pass the constructor flags (``allow_egress=True`` ...) **or** set
``AGENTKIT_SANDBOX_UNSAFE=1`` in the environment. Defaults are deny; the guard raises a
typed exception (``EgressBlocked`` / ``CloudCLIBlocked`` / ``SecretPathBlocked`` /
``WriteBlocked``) inside the child, never reaching the network or the secret file.

Honest limitation
~~~~~~~~~~~~~~~~~
This is *application-layer mediation inside the sandboxed Python interpreter*, not a
kernel-enforced sandbox (no seccomp/landlock on macOS). A child could in principle
bypass the patched helpers with raw syscalls; the product-grade isolation is the cloud
sandbox (CloudBoundary: ``sandbox.live`` needs ``AGENTKIT_TOOL_ID``). What this module
guarantees is that the default harness path never egresses, never runs a cloud-write CLI,
and never touches a shell profile / secret file — and that negative tests prove it.
"""
from __future__ import annotations

import os
import subprocess
import sys
import tempfile
from dataclasses import dataclass, field

MODES = ("read-only", "workspace-write", "danger-full-access")
APPROVALS = ("untrusted", "on-request", "never")

# Master env switch: explicit opt-out, ONLY for tests that need to prove the guard
# itself is what blocks egress. When unset, every deny layer stays on.
UNSAFE_ENV = "AGENTKIT_SANDBOX_UNSAFE"

#: Exception class names surfaced to the child process (kept as strings so the
#: generated sitecustomize is self-contained).
EGRESS_BLOCKED = "EgressBlocked"
CLOUD_CLI_BLOCKED = "CloudCLIBlocked"
SECRET_PATH_BLOCKED = "SecretPathBlocked"
WRITE_BLOCKED = "WriteBlocked"


# Generated sitecustomize injected into every child interpreter. ``{...}`` tokens are
# baked literals; the child then patches socket / subprocess / builtins at startup.
_SITECUSTOMIZE_TEMPLATE = r'''
# --- generated by harness.c09_sandbox; do not edit ---
import builtins as _builtins
import os as _os
import socket as _socket
import subprocess as _subprocess


class EgressBlocked(PermissionError):
    """Outbound network egress denied by the default-deny guard."""


class CloudCLIBlocked(EgressBlocked):
    """Invocation of a known cloud-write CLI denied by the default-deny guard."""


class SecretPathBlocked(EgressBlocked):
    """Read of a shell profile / common secret path denied by the default-deny guard."""


class WriteBlocked(EgressBlocked):
    """Filesystem write denied (read-only sandbox mode)."""


_ALLOW_EGRESS = {allow_egress}
_ALLOW_CLOUD_CLI = {allow_cloud_cli}
_BLOCK_SECRETS = {block_secrets}
_READ_ONLY = {read_only}

_HOME = _os.path.realpath(_os.path.expanduser("~"))

# Filenames / path fragments treated as shell profiles or secret stores. The guard
# matches path *strings only*; it never opens these files.
_SECRET_BASENAMES = (
    ".zshrc", ".zprofile", ".zshenv", ".bashrc", ".bash_profile", ".bash_login",
    ".profile", ".netrc", ".pgpass", ".npmrc", ".pypirc", ".huggingface",
)
_SECRET_PATH_FRAGMENTS = (
    "/.aws/", "/.ssh/", "/.gnupg/", "/.config/gcloud/", "/.config/az/",
    "/.volc/", "/.config/fish/", "/.docker/config.json", "/.huggingface/",
)


def _is_secret_path(target):
    try:
        rp = _os.path.realpath(str(target))
    except Exception:
        return False
    if not rp.startswith(_HOME):
        return False
    rel = "/" + _os.path.relpath(rp, _HOME)  # e.g. "/.zshrc" or "/.aws/credentials"
    if _os.path.basename(rp) in _SECRET_BASENAMES:
        return True
    return any(frag in rel for frag in _SECRET_PATH_FRAGMENTS)


# ---- 1) outbound egress ----
if not _ALLOW_EGRESS:
    def _deny_connect(self, address):
        raise EgressBlocked("sandbox: outbound network egress is denied by default")

    def _deny_connect_ex(self, address):
        try:
            _deny_connect(self, address)
        except EgressBlocked as exc:
            return getattr(exc, "errno", 1) or 1
        return 0

    _socket.socket.connect = _deny_connect
    _socket.socket.connect_ex = _deny_connect_ex


# ---- 2) known cloud-write CLIs ----
_CLOUD_WRITE_ARGV = (
    ("aws", ("s3", "s3api", "ecr", "codepipeline")),
    ("gcloud", ("storage",)),
    ("gsutil", ()),
    ("az", ("storage",)),
    ("tosutil", ()),
    ("tos", ()),
    ("huggingface-cli", ("upload",)),
    ("hf", ("upload",)),
    ("twine", ("upload",)),
    ("npm", ("publish",)),
    ("yarn", ("publish",)),
    ("docker", ("push",)),
    ("git", ("push",)),
)


def _argv_is_cloud_write(argv):
    try:
        head = [str(a) for a in argv]
    except Exception:
        return False
    if not head:
        return False
    prog = _os.path.basename(head[0]).lower()
    rest = [a.lower() for a in head[1:]]
    for name, verbs in _CLOUD_WRITE_ARGV:
        if prog != name:
            continue
        if not verbs or any(r == verbs[0] or r in verbs for r in rest):
            return True
    return False


if not _ALLOW_CLOUD_CLI:
    _orig_popen_init = _subprocess.Popen.__init__

    def _guarded_popen(self, args, *a, **kw):
        argv = args.split() if isinstance(args, str) else list(args)
        if _argv_is_cloud_write(argv):
            raise CloudCLIBlocked(
                "sandbox: cloud-write CLI denied by default: %r" % (argv[:2],))
        return _orig_popen_init(self, args, *a, **kw)

    _subprocess.Popen.__init__ = _guarded_popen


# ---- 3) secret-path reads ----
_orig_open = _builtins.open


def _guarded_open(file, mode="r", *a, **kw):
    if _BLOCK_SECRETS and _is_secret_path(file):
        raise SecretPathBlocked(
            "sandbox: reading shell profile / secret path denied: %r" % (file,))
    if _READ_ONLY and any(ch in mode for ch in "wax+"):
        raise WriteBlocked("sandbox: read-only mode denies writes: %r" % (file,))
    return _orig_open(file, mode, *a, **kw)


_builtins.open = _guarded_open

_orig_os_open = _os.open
_WRITE_FLAGS = (_os.O_WRONLY | _os.O_RDWR | _os.O_CREAT
                | _os.O_EXCL | _os.O_TRUNC)


def _guarded_os_open(path, flags, *a, **kw):
    if _BLOCK_SECRETS and _is_secret_path(path):
        raise SecretPathBlocked(
            "sandbox: reading shell profile / secret path denied: %r" % (path,))
    if _READ_ONLY and (flags & _WRITE_FLAGS):
        raise WriteBlocked("sandbox: read-only mode denies writes: %r" % (path,))
    return _orig_os_open(path, flags, *a, **kw)


_os.open = _guarded_os_open


# ---- 4) read-only mode: no subprocess, no fs mutation, no os.system ----
if _READ_ONLY:
    def _deny_fs_mutate(*a, **kw):
        raise WriteBlocked("sandbox: read-only mode denies filesystem mutation")

    for _name in ("remove", "unlink", "rmdir", "rename", "replace", "mkdir",
                  "makedirs", "truncate", "chmod", "chown", "utime", "rmtree"):
        if hasattr(_os, _name):
            setattr(_os, _name, _deny_fs_mutate)

    def _deny_system(cmd=None, *a, **kw):
        raise WriteBlocked("sandbox: read-only mode denies os.system")

    _os.system = _deny_system

    def _deny_popen(self, args, *a, **kw):
        raise WriteBlocked("sandbox: read-only mode denies subprocess execution")

    _subprocess.Popen.__init__ = _deny_popen
'''


@dataclass
class LocalSandbox:
    """Per-session workspace sandbox with a default-deny guard.

    Security layers default to *deny*. Tests may opt out explicitly via the
    constructor flags or the ``AGENTKIT_SANDBOX_UNSAFE=1`` env master switch.
    """

    mode: str = "workspace-write"
    approval: str = "on-request"
    allow_egress: bool = False
    allow_cloud_cli: bool = False
    allow_secret_read: bool = False
    _workspaces: dict[str, str] = field(default_factory=dict)
    _guard_dir: str = field(default="", repr=False)

    def __post_init__(self) -> None:
        if self.mode not in MODES:
            raise ValueError(f"unknown sandbox mode: {self.mode!r}; choose from {MODES}")
        if self.approval not in APPROVALS:
            raise ValueError(f"unknown approval: {self.approval!r}; choose from {APPROVALS}")
        if os.getenv(UNSAFE_ENV) == "1":
            # explicit master opt-out (test-only)
            self.allow_egress = True
            self.allow_cloud_cli = True
            self.allow_secret_read = True
        self._guard_dir = tempfile.mkdtemp(prefix="sandbox_guard_")
        self._write_sitecustomize()

    # ------------------------------------------------------------------ guard --
    def _write_sitecustomize(self) -> None:
        read_only = self.mode == "read-only"
        src = _SITECUSTOMIZE_TEMPLATE.format(
            allow_egress=repr(bool(self.allow_egress)),
            allow_cloud_cli=repr(bool(self.allow_cloud_cli)),
            block_secrets=repr(not self.allow_secret_read),
            read_only=repr(read_only),
        )
        with open(os.path.join(self._guard_dir, "sitecustomize.py"), "w") as f:
            f.write(src)

    def guard_policy(self) -> dict:
        """Machine-readable snapshot of which deny layers are active."""
        return {
            "egress": "allow" if self.allow_egress else "deny",
            "cloud_cli": "allow" if self.allow_cloud_cli else "deny",
            "secret_read": "allow" if self.allow_secret_read else "deny",
            "fs_write": "deny" if self.mode == "read-only" else "allow",
            "mode": self.mode,
            "approval": self.approval,
        }

    # --------------------------------------------------------------- sessions --
    def workspace(self, session_id: str) -> str:
        if session_id not in self._workspaces:
            d = tempfile.mkdtemp(prefix=f"sandbox_{session_id}_")
            self._workspaces[session_id] = d
        return self._workspaces[session_id]

    def exec_code(self, session_id: str, code: str) -> dict:
        ws = self.workspace(session_id)
        env = os.environ.copy()
        # Inject the mediated sitecustomize into the child interpreter startup.
        env["PYTHONPATH"] = self._guard_dir + os.pathsep + env.get("PYTHONPATH", "")
        env["PYTHONDONTWRITEBYTECODE"] = "1"
        proc = subprocess.run(
            [sys.executable, "-c", code], cwd=ws, env=env, capture_output=True,
            text=True, timeout=20)
        return {
            "session_id": session_id,
            "stdout": proc.stdout,
            "stderr": proc.stderr,
            "exit_code": proc.returncode,
            "workspace": ws,
            "guard": self.guard_policy(),
        }

    def can_access(self, resource: str) -> bool:
        if self.approval == "untrusted":
            return False
        return True
